// Command gen-vectors writes deterministic ULID test vectors as Zig source,
// using github.com/oklog/ulid/v2 as the reference implementation.
//
// Usage, from the repository root:
//
//	(cd tools && go run .) > src/tests/vectors_data.zig && zig fmt src/tests/vectors_data.zig
package main

import (
	"fmt"
	"math/rand"

	"github.com/oklog/ulid/v2"
)

const header = `//! Generated by tools/gen-vectors.go from github.com/oklog/ulid/v2. Do not edit.
//! Reference values produced with github.com/oklog/ulid/v2 (Apache-2.0).
//! Regenerate from the repository root with:
//! (cd tools && go run .) > src/tests/vectors_data.zig && zig fmt src/tests/vectors_data.zig

/// A ULID in its text form and the 16 big-endian bytes it encodes.
pub const Vector = struct {
    text: *const [26]u8,
    bytes: [16]u8,
};

pub const vectors = [_]Vector{
`

func emit(id ulid.ULID) {
	fmt.Printf("    .{ .text = %q, .bytes = .{", id.String())
	for i, b := range id {
		if i > 0 {
			fmt.Print(",")
		}
		fmt.Printf(" 0x%02x", b)
	}
	fmt.Print(" } },\n")
}

func fromParts(ms uint64, entropy [10]byte) ulid.ULID {
	var id ulid.ULID
	if err := id.SetTime(ms); err != nil {
		panic(err)
	}
	if err := id.SetEntropy(entropy[:]); err != nil {
		panic(err)
	}
	return id
}

func main() {
	fmt.Print(header)
	defer fmt.Print("};\n")

	var zero, ones [10]byte
	for i := range ones {
		ones[i] = 0xff
	}

	// Edge cases.
	emit(ulid.ULID{})                                  // all zero
	emit(fromParts(ulid.MaxTime(), ones))              // all 0xff
	emit(fromParts(ulid.MaxTime(), zero))              // max timestamp, zero entropy
	emit(fromParts(0, ones))                           // zero timestamp, max entropy
	emit(fromParts(1, zero))                           // smallest non-zero timestamp
	emit(ulid.MustParse("01ARZ3NDEKTSV4RRFFQ69G5FAV")) // spec example

	// Single-bit patterns across all 128 bits.
	for bit := 0; bit < 128; bit += 7 {
		var id ulid.ULID
		id[bit/8] = 0x80 >> (bit % 8)
		emit(id)
	}

	// Random values from a fixed seed.
	rng := rand.New(rand.NewSource(0x5eed))
	for i := 0; i < 120; i++ {
		ms := uint64(rng.Int63()) & ulid.MaxTime()
		var e [10]byte
		rng.Read(e[:])
		emit(fromParts(ms, e))
	}

	// Monotonic sequences: several IDs in the same millisecond.
	mono := ulid.Monotonic(rand.New(rand.NewSource(42)), 0)
	for _, ms := range []uint64{1469918176385, 1700000000000, ulid.MaxTime()} {
		for i := 0; i < 15; i++ {
			emit(ulid.MustNew(ms, mono))
		}
	}
}
